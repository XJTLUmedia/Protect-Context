/**
 * An English/中文 term bridge for recall — a dictionary, not embeddings.
 *
 * A keyword is matched literally across `text`, `cmd`, and `digest`. That left
 * one measured gap: a 中文 query never reached an English row claiming the same
 * rule (`生产库` found nothing in "never run destructive SQL on the production
 * database") because the two rows share no characters. Real cross-lingual
 * paraphrase needs a learned model, which SPEC excludes, so this module does the
 * deterministic half: a term table, applied at query time.
 *
 * - A dictionary lookup, applied at query time. Nothing is translated when a row
 *   is stored, so the JSONL format is unchanged and an old store needs no
 *   migration.
 * - Symmetric: `生产库` expands to `production database` and `production`;
 *   `deploy` expands to `部署`.
 * - Two tiers: `data/curated.tsv` holds the vocabulary this tool records and is
 *   returned first, uncapped; below it a table derived from CC-CEDICT (64k
 *   pairs) reaches ordinary words, capped per query because a dictionary sense
 *   can be the wrong one for this domain (CC-CEDICT gives 分所 for "branch").
 *
 * `src/protect_context/lexicon.tsv` is generated by `scripts/build_lexicon.mjs`
 * and read by BOTH runtimes, so the Python and TypeScript tables cannot drift.
 */

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { stem } from "./stem.ts";

/** Shipped inside the Python package and listed in package.json `files`, so the
 *  installed extension resolves the same bytes the CLI reads. */
const LEXICON_PATH = join(dirname(fileURLToPath(import.meta.url)), "../../src/protect_context/lexicon.tsv");

/** How many dictionary senses one query term may expand to. */
export const DICTIONARY_CAP = 6;

/** Below two characters a keyword bridges nothing: Chinese substring matching
 *  runs both ways, so 库 would reach 数据库 *and* 生产库 and then English rows for
 *  each. That is a guess, not a lookup; literal matching still works. */
const MIN_BRIDGE_CHARS = 2;

const CURATED_MARK = "# --- curated";
const DICTIONARY_MARK = "# --- dictionary";

interface Tables {
  curated: ReadonlyArray<readonly [string, string]>;
  dictionary: ReadonlyArray<readonly [string, string]>;
  stemmed: ReadonlyArray<readonly [string, string, string]>;
}

let cached: Tables | null = null;

/** (curated, dictionary) pairs in file order. Parsed once per process. */
function tables(): Tables {
  if (cached) return cached;
  const curated: Array<[string, string]> = [];
  const dictionary: Array<[string, string]> = [];
  let bucket: Array<[string, string]> | null = null;
  let text = "";
  try {
    text = readFileSync(LEXICON_PATH, "utf8");
  } catch {
    // A packaging mistake must not take the read path down with it: recall
    // still works, it just loses the bridge.
    cached = { curated, dictionary, stemmed: [] };
    return cached;
  }
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith(CURATED_MARK)) {
      bucket = curated;
      continue;
    }
    if (line.startsWith(DICTIONARY_MARK)) {
      bucket = dictionary;
      continue;
    }
    if (bucket === null || line === "" || line.startsWith("#")) continue;
    const tab = line.indexOf("\t");
    if (tab <= 0) continue;
    const english = line.slice(0, tab);
    const chinese = line.slice(tab + 1);
    if (english === "" || chinese === "") continue;
    bucket.push([english, chinese]);
  }
  cached = {
    curated,
    dictionary,
    // Stems are compared, not full words: a dictionary row keyed on
    // "deployment" must answer the query "deploy". Done once, at load.
    stemmed: dictionary.map(([english, chinese]) => [stem(english), english, chinese] as const),
  };
  return cached;
}

export function curatedPairs(): ReadonlyArray<readonly [string, string]> {
  return tables().curated;
}

export function dictionaryPairs(): ReadonlyArray<readonly [string, string]> {
  return tables().dictionary;
}

function isAscii(term: string): boolean {
  return /^[\x00-\x7f]*$/.test(term);
}

function wordStart(haystack: string, keyword: string): boolean {
  if (keyword === "") return false;
  let start = 0;
  for (;;) {
    const index = haystack.indexOf(keyword, start);
    if (index < 0) return false;
    if (index === 0) return true;
    const before = haystack.slice(0, index);
    const last = Array.from(before).at(-1) ?? "";
    if (!/^[\p{L}\p{N}]$/u.test(last)) return true;
    start = index + 1;
  }
}

/**
 * True when `keyword` names the same term as a glossary `entry` side.
 *
 * Script must agree: a 中文 keyword is matched against the 中文 side only, so the
 * lookup is one hop and never chains a translation of a translation.
 */
export function termMatches(entry: string, keyword: string): boolean {
  const foldedEntry = entry.toLowerCase();
  const foldedKeyword = keyword.toLowerCase();
  if (foldedEntry === "" || foldedKeyword === "") return false;
  if (isAscii(foldedEntry) !== isAscii(foldedKeyword)) return false;
  if (!isAscii(foldedKeyword)) {
    // No word starts in Chinese: substring in either direction, so a query for
    // 生产 also reaches the more specific 生产库 entry.
    return foldedKeyword.includes(foldedEntry) || foldedEntry.includes(foldedKeyword);
  }
  if (wordStart(foldedEntry, foldedKeyword)) return true;
  const stemmed = stem(foldedEntry);
  return stemmed !== "" && stemmed === stem(foldedKeyword);
}

function curatedCounterparts(keyword: string, seen: Set<string>, found: string[]): void {
  for (const [english, chinese] of tables().curated) {
    let candidate: string;
    if (termMatches(english, keyword)) candidate = chinese;
    else if (termMatches(chinese, keyword)) candidate = english;
    else continue;
    const key = candidate.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    found.push(candidate);
  }
}

function dictionaryCounterparts(keyword: string, seen: Set<string>, found: string[]): void {
  let added = 0;
  if (isAscii(keyword)) {
    const target = stem(keyword.toLowerCase());
    for (const [entryStem, , chinese] of tables().stemmed) {
      if (entryStem !== target) continue;
      const key = chinese.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      found.push(chinese);
      added += 1;
      if (added >= DICTIONARY_CAP) return;
    }
    return;
  }
  const folded = keyword.toLowerCase();
  for (const [english, chinese] of tables().dictionary) {
    const foldedChinese = chinese.toLowerCase();
    if (!(foldedChinese.includes(folded) || folded.includes(foldedChinese))) continue;
    const key = english.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    found.push(english);
    added += 1;
    if (added >= DICTIONARY_CAP) return;
  }
}

/**
 * Counterparts of `keyword` in the other language.
 *
 * Curated pairs come first, in file order, then dictionary senses capped at
 * `DICTIONARY_CAP`. The keyword itself is never returned, so a pair whose sides
 * differ only in case cannot produce a self-match.
 */
export function translationsOf(keyword: string): string[] {
  const folded = keyword.toLowerCase();
  if (folded.trim().length < MIN_BRIDGE_CHARS) return [];
  const seen = new Set([folded]);
  const found: string[] = [];
  curatedCounterparts(keyword, seen, found);
  dictionaryCounterparts(keyword, seen, found);
  return found;
}
