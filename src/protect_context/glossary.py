"""An English/中文 term bridge for recall — a dictionary, not embeddings.

A keyword is matched literally across ``text``, ``cmd``, and ``digest``. That
left one measured gap: a 中文 query never reached an English row claiming the
same rule (``生产库`` found nothing in "never run destructive SQL on the
production database") because the two rows share no characters. Real
cross-lingual paraphrase needs a learned model, which SPEC excludes, so this
module does the deterministic half: a term table, applied at query time.

What this is:

- **A dictionary lookup, applied at query time.** Nothing is translated when a
  row is stored, so the JSONL format is unchanged and an old store needs no
  migration. The query term is expanded to its counterparts; the row still has
  to contain one of them under the normal word-start/stem rule.
- **Symmetric.** ``生产库`` expands to ``production database`` and
  ``production``; ``deploy`` expands to ``部署``.
- **Two tiers.** ``data/curated.tsv`` holds the vocabulary this tool actually
  records and is returned first, uncapped. Below it sits a table derived from
  CC-CEDICT (the ``cc-cedict`` npm package, a build-time dependency only): 64k
  pairs that reach ordinary words the curated list never listed. A dictionary
  sense can be the wrong one for this domain (CC-CEDICT gives 分所 for
  "branch"), which is exactly why the curated tier comes first and why the
  dictionary tier is capped per query.
- **Bounded and honest.** Only the pairs in the table bridge. A paraphrase
  outside it still misses, exactly as before — this is recall for written-down
  terms, not a translation model.

``src/protect_context/lexicon.tsv`` is generated by ``scripts/build_lexicon.mjs``
and read by BOTH runtimes, so the Python and TypeScript tables cannot drift.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from . import stem as stemmer

# Shipped inside the package (the wheel picks it up as package data) and listed
# in package.json `files`, so the extension resolves the same bytes at
# `../../src/protect_context/lexicon.tsv` from its installed location.
LEXICON_PATH = Path(__file__).with_name("lexicon.tsv")

# How many dictionary senses one query term may expand to. The curated tier is
# never capped: it is small and deliberate. Six is enough to reach a synonym
# without turning one keyword into a fan of unrelated rows.
DICTIONARY_CAP = 6

_CURATED_MARK = "# --- curated"
_DICTIONARY_MARK = "# --- dictionary"

# Below two characters a keyword bridges nothing: Chinese substring matching runs
# in either direction, so 库 would reach 数据库 *and* 生产库 and then English rows
# for each of them. That is a guess, not a lookup; literal matching still works.
_MIN_BRIDGE_CHARS = 2


def _is_ascii(term: str) -> bool:
    return term.isascii()


@lru_cache(maxsize=1)
def _tables() -> tuple[tuple[tuple[str, str], ...], tuple[tuple[str, str], ...]]:
    """(curated, dictionary) pairs in file order. Parsed once per process."""
    curated: list[tuple[str, str]] = []
    dictionary: list[tuple[str, str]] = []
    bucket: list[tuple[str, str]] | None = None
    try:
        text = LEXICON_PATH.read_text(encoding="utf-8")
    except OSError:
        # A packaging mistake must not take the read path down with it: recall
        # still works, it just loses the bridge. tests/test_recall.py pins this.
        return (), ()
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith(_CURATED_MARK):
            bucket = curated
            continue
        if line.startswith(_DICTIONARY_MARK):
            bucket = dictionary
            continue
        if bucket is None or line == "" or line.startswith("#"):
            continue
        english, _, chinese = line.partition("\t")
        if english and chinese:
            bucket.append((english, chinese))
    return tuple(curated), tuple(dictionary)


def curated_pairs() -> tuple[tuple[str, str], ...]:
    """The hand-maintained tier, in file order."""
    return _tables()[0]


def dictionary_pairs() -> tuple[tuple[str, str], ...]:
    """The CC-CEDICT tier, in file order."""
    return _tables()[1]


@lru_cache(maxsize=1)
def _stemmed_dictionary() -> tuple[tuple[str, str, str], ...]:
    """(stem of the English side, English, 中文) so a search never re-stems.

    Stems are compared, not full words: a dictionary row keyed on "deployment"
    must answer the query "deploy". Word-start matching stays with the curated
    tier, where the pairs are short and deliberate.
    """
    return tuple((stemmer.stem(english), english, chinese) for english, chinese in _tables()[1])


def _word_start(haystack: str, keyword: str) -> bool:
    """True when ``keyword`` starts a word in ``haystack`` (ASCII rule)."""
    if not keyword:
        return False
    start = 0
    while True:
        index = haystack.find(keyword, start)
        if index < 0:
            return False
        if index == 0 or not haystack[index - 1].isalnum():
            return True
        start = index + 1


def term_matches(entry: str, keyword: str) -> bool:
    """True when ``keyword`` names the same term as a glossary ``entry`` side.

    Script must agree: a 中文 keyword is matched against the 中文 side only, so
    the lookup is one hop and never chains a translation of a translation.
    """
    entry = entry.casefold()
    keyword = keyword.casefold()
    if not entry or not keyword or _is_ascii(entry) != _is_ascii(keyword):
        return False
    if not _is_ascii(keyword):
        # No word starts in Chinese: substring in either direction, so a query
        # for 生产 also reaches the more specific 生产库 entry.
        return keyword in entry or entry in keyword
    if _word_start(entry, keyword):
        return True
    stemmed = stemmer.stem(entry)
    return stemmed != "" and stemmed == stemmer.stem(keyword)


def _curated_counterparts(keyword: str, seen: set[str], found: list[str]) -> None:
    for english, chinese in _tables()[0]:
        if term_matches(english, keyword):
            candidate = chinese
        elif term_matches(chinese, keyword):
            candidate = english
        else:
            continue
        key = candidate.casefold()
        if key in seen:
            continue
        seen.add(key)
        found.append(candidate)


def _dictionary_counterparts(keyword: str, seen: set[str], found: list[str]) -> None:
    """Add up to ``DICTIONARY_CAP`` dictionary senses, in file order."""
    added = 0
    if _is_ascii(keyword):
        target = stemmer.stem(keyword.casefold())
        for entry_stem, _english, chinese in _stemmed_dictionary():
            if entry_stem != target:
                continue
            key = chinese.casefold()
            if key in seen:
                continue
            seen.add(key)
            found.append(chinese)
            added += 1
            if added >= DICTIONARY_CAP:
                return
        return
    folded = keyword.casefold()
    for english, chinese in _tables()[1]:
        if not (chinese.casefold() in folded or folded in chinese.casefold()):
            continue
        key = english.casefold()
        if key in seen:
            continue
        seen.add(key)
        found.append(english)
        added += 1
        if added >= DICTIONARY_CAP:
            return


def translations(keyword: str) -> tuple[str, ...]:
    """Counterparts of ``keyword`` in the other language.

    Curated pairs come first, in file order, then dictionary senses capped at
    ``DICTIONARY_CAP``. The keyword itself is never returned, so a pair whose
    sides differ only in case cannot produce a self-match.
    """
    folded = keyword.casefold()
    if len(folded.strip()) < _MIN_BRIDGE_CHARS:
        return ()
    seen: set[str] = {folded}
    found: list[str] = []
    _curated_counterparts(keyword, seen, found)
    _dictionary_counterparts(keyword, seen, found)
    return tuple(found)
